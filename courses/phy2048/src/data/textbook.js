/** The citation for a section number, such as '5.4', or null when the book has no such section. */
export function citeSection(section) {
  const title = SECTION_TITLES[section];
  return title ? { book: 'openstax1', section, title } : null;
}

/** The citation for a topic tag, or null. */
export function citation(topic) {
  const section = TOPICS[topic];
  return section ? citeSection(section) : null;
}

export function citationText(topic) {
  const c = citation(topic);
  return c ? `${BOOKS[c.book].short} §${c.section}` : null;
}
