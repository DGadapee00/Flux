#!/usr/bin/env node
/**
 * Writes src/thermo/glenn-data.js: NASA Glenn 9-coefficient polynomials for N₂, O₂, Ar and CH₄.
 *
 *   node scripts/nasa9-glenn.mjs <path to thermo.inp>
 *
 * Source: B. J. McBride, M. J. Zehe and S. Gordon, "NASA Glenn Coefficients for Calculating
 * Thermodynamic Properties of Individual Species", NASA/TP-2002-211556 (2002), as distributed in
 * NASA's CEA database file data/thermo.inp, github.com/nasa/cea at commit
 * 2f79a647e85737742fb08a127da00d1ea1d069da (Apache 2.0). The script refuses a file whose SHA-256
 * differs. Fetch it with:
 *   curl -O https://raw.githubusercontent.com/nasa/cea/2f79a647e85737742fb08a127da00d1ea1d069da/data/thermo.inp
 *
 * Record format (NASA/TP-2002-211556, Appendix A), fixed columns:
 *   line 1: species name in columns 1–24, then comments
 *   line 2: number of temperature intervals (cols 1–2), reference code, formula, phase flag,
 *           molecular weight in g/mol (cols 53–65), heat of formation at 298.15 K in J/mol (66–80)
 *   per interval, three lines:
 *           T_low (cols 1–11), T_high (12–22), the exponents, H(298.15) − H(0)
 *           a1..a5, five 16-column fields
 *           a6, a7, a blank field, then b1, b2
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SHA256 = 'fa7746572952d74e249e818a82a35c113829742fb421a308e167185528884363';
const COMMIT = '2f79a647e85737742fb08a127da00d1ea1d069da';
/** thermo.inp name → the name used here. */
const WANT = { N2: 'N2', O2: 'O2', Ar: 'AR', CH4: 'CH4' };

const file = process.argv[2];
if (!file) {
  console.error('usage: node scripts/nasa9-glenn.mjs <path to thermo.inp>');
  process.exit(2);
}
const raw = fs.readFileSync(file);
const sha = crypto.createHash('sha256').update(raw).digest('hex');
if (sha !== SHA256) {
  console.error(`thermo.inp: SHA-256 ${sha}, expected ${SHA256} (nasa/cea at ${COMMIT}).`);
  process.exit(1);
}

const lines = raw.toString('latin1').split(/\r?\n/);
const num = (s) => Number(s.trim().replace(/D/gi, 'E'));
const fields = (line, n) => Array.from({ length: n }, (_, k) => line.slice(16 * k, 16 * k + 16));

const species = {};
for (let i = 0; i < lines.length; i++) {
  const name = lines[i].slice(0, 24).trim().split(/\s+/)[0];
  const id = WANT[name];
  if (!id || species[id] || lines[i].startsWith('!')) continue;
  const head = lines[i + 1].padEnd(80);
  const intervals = Number(head.slice(0, 2));
  const W = Number((Number(head.slice(52, 65)) / 1000).toPrecision(12));
  const dfH = Number(head.slice(65, 80));
  const ranges = [];
  for (let k = 0; k < intervals; k++) {
    const t = lines[i + 2 + 3 * k].padEnd(80);
    const c1 = lines[i + 3 + 3 * k].padEnd(80);
    const c2 = lines[i + 4 + 3 * k].padEnd(80);
    const exps = t.slice(23, 63).trim().split(/\s+/).map(Number);
    if (exps.join() !== '-2,-1,0,1,2,3,4,0') throw new Error(`${name}: unexpected exponents ${exps.join()}`);
    const [a6, a7, , b1, b2] = fields(c2, 5);
    ranges.push({
      T_low: Number(t.slice(0, 11)),
      T_high: Number(t.slice(11, 22)),
      a: [...fields(c1, 5).map(num), num(a6), num(a7)],
      b: [num(b1), num(b2)],
    });
  }
  species[id] = { W, dfH, ranges };
  i += 1 + 3 * intervals;
}
const missing = Object.values(WANT).filter((id) => !species[id]);
if (missing.length) {
  console.error(`not found in thermo.inp: ${missing.join(', ')}`);
  process.exit(1);
}

const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '../src/thermo/glenn-data.js');
fs.writeFileSync(
  out,
  `/**
 * NASA Glenn 9-coefficient polynomials. Generated by scripts/nasa9-glenn.mjs; do not edit.
 *
 * Source: B. J. McBride, M. J. Zehe and S. Gordon, NASA/TP-2002-211556 (2002), as distributed in
 * NASA's CEA database data/thermo.inp, github.com/nasa/cea at commit ${COMMIT}
 * (Apache 2.0; SHA-256 ${SHA256}).
 *
 *   cp/R = a1 T⁻² + a2 T⁻¹ + a3 + a4 T + a5 T² + a6 T³ + a7 T⁴
 *   h/(RT) = −a1 T⁻² + a2 ln(T)/T + a3 + a4 T/2 + a5 T²/3 + a6 T³/4 + a7 T⁴/5 + b1/T
 *   s°/R = −a1 T⁻²/2 − a2 T⁻¹ + a3 ln T + a4 T + a5 T²/2 + a6 T³/3 + a7 T⁴/4 + b2   (s° at 1 bar)
 *
 * W is in kg/mol and dfH, the heat of formation at 298.15 K, in J/mol, both as the file gives them.
 * Ranges are as the file gives them; the first starts at 200 K for all four species.
 */
export const GLENN = Object.freeze(${JSON.stringify(species, null, 2)});
`,
);
console.log(`wrote ${path.relative(process.cwd(), out)}: ${Object.keys(species).join(', ')}`);
