#!/usr/bin/env node
/**
 * Writes src/thermo/nasa7-data.js: NASA 7-coefficient polynomials from GRI-Mech 3.0.
 *
 *   node scripts/nasa7-gri.mjs <path to gri30.inp>
 *
 * The input is Cantera 2.4's copy of GRI-Mech 3.0 (data/inputs/gri30.inp), the same file the engine
 * repo's Sim/tools/nasa7.py read for Sim/data/thermo_nasa7.json. The script refuses a file whose
 * SHA-256 differs, so the seven species both repos carry come out identical; test/thermo.test.js
 * checks that against the engine's file.
 *
 * Fetch it with:
 *   curl -O https://raw.githubusercontent.com/Cantera/cantera/2.4/data/inputs/gri30.inp
 *
 * Record format (CHEMKIN, four 80-column lines, '1'..'4' in column 80): name in columns 1–18,
 * elements in columns 25–44 as four [2-character symbol, 3-digit count] fields, T_low, T_high,
 * T_common in columns 46–73; then 14 coefficients in 15-character fields, a1..a7 for the high
 * range and a1..a7 for the low range. Molar masses come from the element counts and the IUPAC
 * abridged standard atomic weights (2013), as in the engine's file.
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SHA256 = '0bfc72f546309d1388f21a30fcb7c31372d7de6e92d60d028d8f3e8499ddf774';
const SPECIES = ['O2', 'N2', 'AR', 'CO2', 'H2O', 'CH4', 'CO', 'H2', 'H', 'O', 'OH'];
const ATOMIC_WEIGHT = { H: 1.008, C: 12.011, N: 14.007, O: 15.999, AR: 39.95 };

const file = process.argv[2];
if (!file) {
  console.error('usage: node scripts/nasa7-gri.mjs <path to gri30.inp>');
  process.exit(2);
}
const raw = fs.readFileSync(file);
const sha = crypto.createHash('sha256').update(raw).digest('hex');
if (sha !== SHA256) {
  console.error(`gri30.inp: SHA-256 ${sha}, expected ${SHA256}. This is not the file the engine repo used.`);
  process.exit(1);
}

const lines = raw.toString('latin1').split(/\r?\n/);
const start = lines.findIndex((l) => l.trim().toUpperCase().startsWith('THERMO'));
const block = [];
for (const l of lines.slice(start + 2)) {
  if (l.trim().toUpperCase().startsWith('END')) break;
  block.push(l);
}

const recs = {};
for (let i = 0; i < block.length; i++) {
  const l1 = block[i].padEnd(80);
  if (l1[79] !== '1') continue;
  const name = l1.slice(0, 18).trim().split(/\s+/)[0];
  const elements = {};
  for (let k = 0; k < 4; k++) {
    const field = l1.slice(24 + 5 * k, 29 + 5 * k);
    const sym = field.slice(0, 2).trim().toUpperCase();
    const cnt = field.slice(2).trim();
    if (sym && cnt && sym !== '0' && Number(cnt) !== 0) elements[sym] = (elements[sym] || 0) + Math.trunc(Number(cnt));
  }
  const tLow = Number(l1.slice(45, 55));
  const tHigh = Number(l1.slice(55, 65));
  const tMid = Number(l1.slice(65, 73).trim() || 1000);
  const nums = [];
  for (const l of block.slice(i + 1, i + 4)) {
    const row = l.padEnd(80);
    for (let k = 0; k < 5; k++) {
      const f = row.slice(15 * k, 15 * k + 15).trim();
      if (f) nums.push(Number(f.replace(/D/gi, 'E')));
    }
  }
  recs[name] = { elements, T_low: tLow, T_mid: tMid, T_high: tHigh, high: nums.slice(0, 7), low: nums.slice(7, 14) };
  i += 3;
}

const species = {};
for (const s of SPECIES) {
  const r = recs[s];
  if (!r) {
    console.error(`species ${s} is not in the THERMO block`);
    process.exit(1);
  }
  const W = Object.entries(r.elements).reduce((sum, [e, n]) => sum + ATOMIC_WEIGHT[e] * n, 0) / 1000;
  species[s] = { W: Math.round(W * 1e9) / 1e9, ...r };
}

const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '../src/thermo/nasa7-data.js');
const body = `/**
 * NASA 7-coefficient polynomials from GRI-Mech 3.0. Generated by scripts/nasa7-gri.mjs; do not edit.
 *
 * Source: G. P. Smith, D. M. Golden, M. Frenklach, et al., GRI-Mech 3.0, thermo30.dat,
 * http://combustion.berkeley.edu/gri-mech/version30/text30.html, read from Cantera 2.4's
 * data/inputs/gri30.inp (SHA-256 ${SHA256}),
 * the file the engine repo's Sim/data/thermo_nasa7.json was generated from.
 *
 *   cp/R = a1 + a2 T + a3 T² + a4 T³ + a5 T⁴
 *   h/(RT) = a1 + a2 T/2 + a3 T²/3 + a4 T³/4 + a5 T⁴/5 + a6/T
 *   s°/R = a1 ln T + a2 T + a3 T²/2 + a4 T³/3 + a5 T⁴/4 + a7      (s° at 1 bar)
 *
 * 'low' applies for T_low ≤ T < T_mid and 'high' for T_mid ≤ T ≤ T_high. W is in kg/mol, from the
 * IUPAC abridged standard atomic weights (2013): ${Object.entries(ATOMIC_WEIGHT).map(([e, w]) => `${e} ${w}`).join(', ')}.
 * h includes the enthalpy of formation, so h(298.15 K) is ΔfH° for each species.
 */
export const NASA7 = Object.freeze(${JSON.stringify(species, null, 2)});
`;
fs.writeFileSync(out, body);
console.log(`wrote ${path.relative(process.cwd(), out)}: ${SPECIES.join(', ')}`);
